import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import mongoose from 'mongoose';
import env from '../config/env';
import User from '../models/User';
import Business from '../models/Business';
import Service from '../models/Service';
import Product from '../models/Product';
import Booking from '../models/Booking';
import Client from '../models/Client';
import StaffProfile from '../models/StaffProfile';
import WebsiteMutation from '../models/WebsiteMutation';
import OfflineConflict from '../models/OfflineConflict';
import app from '../app';
import Notification from '../models/Notification';
import { syncWebsiteChange, WebsiteChange } from '../services/website-sync.service';

async function main() {
  const dbName = 'website_offline_test_' + randomUUID().replaceAll('-', '').slice(0, 16);
  await mongoose.connect(env.MONGO_URI, { dbName, serverSelectionTimeoutMS: 15000 });
  try {
    await Promise.all([User.init(), Business.init(), Service.init(), Product.init(), Booking.init(), Client.init(), StaffProfile.init(), WebsiteMutation.init(), OfflineConflict.init(), Notification.init()]);
    const owner = await User.create({ firebaseUid: 'offline-owner', email: 'owner@example.test', fullName: 'Owner', roles: ['owner'] });
    const other = await User.create({ firebaseUid: 'offline-other', email: 'other@example.test', fullName: 'Other', roles: ['owner'] });
    const shop = await Business.create({ ownerId: owner._id, name: 'Offline test salon', type: 'shop', productsEnabled: true, location: { type: 'Point', coordinates: [38, 9] } });
    const shopId = String(shop._id), prefix = '/dashboard/' + shopId;
    const sync = (change: WebsiteChange) => syncWebsiteChange(owner, shopId, change);
    const create: WebsiteChange = { key: randomUUID(), method: 'POST', path: prefix + '/products', body: { name: 'Test shampoo', price: 100, stockQuantity: 5 } };
    const [first, second] = await Promise.all([sync(create), sync(create)]);
    assert.equal(first._id, second._id); assert.equal(await Product.countDocuments(), 1);
    await assert.rejects(sync({ ...create, body: { ...create.body, price: 200 } }), (e: any) => e.statusCode === 409);
    await assert.rejects(syncWebsiteChange(other, shopId, { ...create, key: randomUUID() }), (e: any) => e.statusCode === 403);
    await assert.rejects(sync({ key: randomUUID(), method: 'PATCH', path: '/admin/users/anything', body: {} }), (e: any) => e.statusCode === 400);
    const edit: WebsiteChange = { key: randomUUID(), method: 'PATCH', path: prefix + '/products/' + first._id, body: { stockQuantity: 9 }, base: { id: first._id, updatedAt: first.updatedAt } };
    await Product.updateOne({ _id: first._id }, { $set: { stockQuantity: 4 } });
    await assert.rejects(sync(edit), (e: any) => e.statusCode === 409);
    assert.equal((await Product.findById(first._id))?.stockQuantity, 4);
    assert.equal(await WebsiteMutation.countDocuments({ key: edit.key }), 0);
    const client = await Client.create({ businessId: shopId, fullName: 'Walk in', phoneNumber: '+251900000000' });
    const clientRaw = client.toObject() as any;
    const note: WebsiteChange = { key: randomUUID(), method: 'PATCH', path: prefix + '/clients/' + client._id + '/notes', body: { notes: 'Prefers scissors' }, base: { id: String(client._id), updatedAt: clientRaw.updatedAt.toISOString() } };
    await sync(note); await sync(note);
    assert.equal((await Client.findById(client._id))?.notes, 'Prefers scissors');
    const service = await Service.create({ businessId: shopId, name: 'Haircut', duration: 30, basePrice: 200 });
    await StaffProfile.create({ businessId: shopId, staffId: 'offline-staff', services: [service._id], isActive: true });
    const day = new Date(); day.setUTCDate(day.getUTCDate()+2); day.setUTCHours(7,0,0,0);
    const from = day.toISOString(), to = new Date(+day+1800000).toISOString();
    const walk: WebsiteChange = { key: randomUUID(), method: 'POST', path: prefix + '/walk-in', body: { serviceIds: [String(service._id)], staffPlan: [{ staffId: 'offline-staff', serviceId: String(service._id), startTime: from, endTime: to }], startTime: from, endTime: to, fullName: 'Offline Client', phoneNumber: '+251911111111', paymentMethod: 'cash' } };
    const booking = await sync(walk);
    assert.equal((await sync(walk))._id, booking._id);
    assert.equal(await Booking.countDocuments(), 1);
    const conflicted = { ...walk, key: randomUUID(), body: { ...walk.body, fullName: 'Do not save me', phoneNumber: '+251922222222' } };
    await assert.rejects(sync(conflicted), (e: any) => e.statusCode === 409);
    assert.equal(await Client.countDocuments({ phoneNumber: '+251922222222' }), 0, 'failed walk-in rolls its client back too');
    const product = (await Product.findById(first._id))!.toObject() as any;
    const cash: WebsiteChange = { key: randomUUID(), method: 'PATCH', path: '/bookings/' + booking._id + '/checkout', expectedTotal: 300, base: { id: booking._id, updatedAt: booking.updatedAt, version: booking.offlineVersion }, body: { products: [{ productId: first._id, quantity: 1 }], paymentMethod: 'cash' } };
    await assert.rejects(sync({ ...cash, key: randomUUID(), expectedTotal: 1 }), (e: any) => e.statusCode === 409);
    assert.equal((await Booking.findById(booking._id))?.paymentStatus, 'unpaid', 'price conflict rolls cash and stock back');
    await sync(cash); await sync(cash);
    assert.equal((await Product.findById(first._id))?.stockQuantity, product.stockQuantity - 1);
    assert.equal((await Client.findOne({ phoneNumber: '+251911111111' }))?.totalSpend, 300);
    assert.equal((await Booking.findById(booking._id))?.paymentStatus, 'paid');
    const profile = (await StaffProfile.findOne({ staffId: 'offline-staff' }))!.toObject() as any;
    const staff: WebsiteChange = { key: randomUUID(), method: 'PATCH', path: prefix + '/staff/offline-staff/visibility', body: { isOnlineVisible: false }, base: { id: String(profile._id), updatedAt: profile.updatedAt.toISOString() } };
    await sync(staff);
    assert.equal((await StaffProfile.findById(profile._id))?.isOnlineVisible, false);
    const staffUser = await User.create({firebaseUid:'offline-staff',fullName:'Offline Staff',email:'staff@example.test',roles:['staff']});
    await StaffProfile.updateOne({staffId:'offline-staff'},{$set:{permissionLevel:'high'}});
    process.env.NODE_ENV='development';
    const server=app.listen(0,'127.0.0.1');await new Promise<void>(resolve=>server.once('listening',resolve));
    const base='http://127.0.0.1:'+(server.address() as any).port+'/api/v1';
    const call=async(user:any,path:string,method='GET',body?:any)=>{const response=await fetch(base+path,{method,headers:{'x-dev-user-id':String(user._id),'Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});return {status:response.status,body:await response.json()};};
    try {
      const failedStaff={...walk,key:randomUUID()};
      assert.equal((await call(staffUser,'/website-sync/'+shopId,'POST',failedStaff)).status,409);
      assert.equal((await call(staffUser,'/website-sync/'+shopId,'POST',failedStaff)).status,409);
      const queue=await call(owner,'/website-sync/conflicts');assert.equal(queue.status,200);
      const issue=queue.body.data.find((issue:any)=>issue.key===failedStaff.key);assert.ok(issue);
      assert.equal(await Notification.countDocuments({eventKey:'offline-conflict:'+issue._id}),1,'conflict alert deduplicated');
      assert.equal((await call(other,'/website-sync/conflicts')).body.data.length,0,'other owner cannot see conflict');
      const moved=JSON.parse(JSON.stringify(failedStaff));moved.key=randomUUID();moved.resolveConflictId=issue._id;
      moved.body.startTime=new Date(+day+3600000).toISOString();moved.body.endTime=new Date(+day+5400000).toISOString();moved.body.staffPlan[0].startTime=moved.body.startTime;moved.body.staffPlan[0].endTime=moved.body.endTime;
      const resolved=await call(owner,'/website-sync/'+shopId,'POST',moved);assert.equal(resolved.status,200,JSON.stringify(resolved.body));
      const original=await call(staffUser,'/website-sync/'+shopId,'POST',failedStaff);assert.equal(original.status,200);assert.equal(original.body.data._id,resolved.body.data._id);
      assert.equal(await Booking.countDocuments(),2,'resolution never duplicates original booking');
      const cancelled={...walk,key:randomUUID()};assert.equal((await call(staffUser,'/website-sync/'+shopId,'POST',cancelled)).status,409);
      const cancelIssue=(await call(owner,'/website-sync/conflicts')).body.data.find((issue:any)=>issue.key===cancelled.key);
      assert.equal((await call(other,`/website-sync/${shopId}/conflicts/${cancelIssue._id}`,'DELETE')).status,403);
      assert.equal((await call(owner,`/website-sync/${shopId}/conflicts/${cancelIssue._id}`,'DELETE')).status,200);
      assert.equal((await call(staffUser,'/website-sync/'+shopId,'POST',cancelled)).body.data.cancelledLocal,true);
      assert.equal(await Booking.countDocuments(),2,'local cancellation never removes online booking');
      await StaffProfile.updateOne({staffId:'offline-staff'},{$set:{permissionLevel:'low'}});
      assert.equal((await call(staffUser,'/website-sync/'+shopId,'POST',{...walk,key:randomUUID()})).status,403);
    } finally {await new Promise<void>(resolve=>server.close(()=>resolve()));}
    console.log('Website offline integration passed: concurrent retries, key misuse, ownership, allowlist, stale edits, notes, walk-in rollback, booking conflict, cash/stock deduplication, Firebase staff IDs.');
  } finally {
    if (!mongoose.connection.name.startsWith('website_offline_test_')) throw new Error('Unexpected test database');
    await mongoose.connection.dropDatabase(); await mongoose.disconnect();
  }
}
main().catch(error => { console.error(error?.name, error?.code || error?.statusCode, error?.message?.includes('mongodb') ? 'Database connection failed' : error?.message); process.exit(1); });
