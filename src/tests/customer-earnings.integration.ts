test("password hashing and money validation", async () => {
  assert.equal(customerPhone("0911223344"), "+251911223344");
  assert.equal(customerPhone("+251 911 223 344"), "+251911223344");
  assert.throws(() => customerPhone("123"));
  const hash = await hashCustomerPassword("correct horse battery");
  assert.ok(await checkCustomerPassword("correct horse battery", hash));
  assert.equal(await checkCustomerPassword("incorrect", hash), false);
  assert.equal(await checkCustomerPassword("incorrect"), false);
  assert.equal(moneyMinor(0.29), 29);
  assert.throws(() => moneyMinor(0.291));
  assert.equal(eligibleEarning({ paymentStatus: "paid", status: "cancelled", completedAt: new Date() }), false);
  assert.equal(eligibleEarning({ paymentStatus: "paid", status: "confirmed" }), false);
  assert.equal(staffCommission({ staffId: "staff", serviceIds: [{ _id: "s", basePrice: 999 }], servicePriceSnapshots: [{ serviceId: "s", unitPrice: 400 }], totalAmount: 350, checkoutItems: [{ quantity: 1, unitPrice: 100 }], tipAmount: 50 }, ["staff"], 25, 10), 60, "commission excludes products/tips from services and adds product commission separately");
  assert.equal(staffCommission({ staffId: "a", serviceIds: [{ _id: "s1", basePrice: 100 }, { _id: "s2", basePrice: 300 }], staffPlan: [{ serviceId: "s1", staffId: "a" }, { serviceId: "s2", staffId: "b" }], totalAmount: 200 }, ["b"], 20), 30, "discounted service revenue is allocated to the assigned staff");
});

