import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import mongoose from "mongoose";
import env from "../config/env";
import app from "../app";
import User from "../models/User";
import Business from "../models/Business";
import Booking from "../models/Booking";
import BookingTicket from "../models/BookingTicket";
import Service from "../models/Service";
import { listCustomerTicketArchive } from "../services/customer-ticket-archive.service";

async function main() {
  process.env.NODE_ENV = "development";
  await mongoose.connect(env.MONGO_URI, { dbName: `archive_test_${randomUUID().replaceAll("-", "").slice(0,16)}`, serverSelectionTimeoutMS: 10000 });
  const server = app.listen(0,"127.0.0.1");
  await new Promise<void>(resolve=>server.once("listening",resolve));
  const base = `http://127.0.0.1:${(server.address() as {port:number}).port}/api/v1`;
  try {
    const customer = await User.create({firebaseUid:"archive-customer",email:"archive-customer@example.test",fullName:"Customer"});
    const other = await User.create({firebaseUid:"archive-other",email:"archive-other@example.test",fullName:"Other"});
    const owner = await User.create({firebaseUid:"archive-owner",email:"archive-owner@example.test",fullName:"Owner",roles:["owner"]});
    const business = await Business.create({ownerId:owner._id,name:"Archive salon",type:"shop",location:{type:"Point",coordinates:[38,9]},homeLocation:{type:"Point",coordinates:[38,9]}});
    const required = await Business.create({ownerId:owner._id,name:"Prepaid salon",type:"shop",requirePrepayment:true,location:{type:"Point",coordinates:[38,9]},homeLocation:{type:"Point",coordinates:[38,9]}});
    const service = await Service.create({businessId:business._id,name:"Haircut",duration:30,basePrice:999});
    const now = new Date();
    const make = (extra: Record<string,unknown>={}) => Booking.create({userId:String(customer._id),businessId:business._id,staffId:String(owner._id),serviceIds:[service._id],servicePriceSnapshots:[{serviceId:service._id,unitPrice:200}],staffPlan:[],totalAmount:200,status:"confirmed",paymentMethod:"cash",paymentStatus:"unpaid",startTime:new Date(+now+3600000),endTime:new Date(+now+5400000),...extra});
    const future = await make();
    const past = await make({startTime:new Date(+now-7200000),endTime:new Date(+now-5400000),paymentStatus:"paid",paidAt:new Date(+now-8000000)});
    await make({startTime:new Date(+now-600000),endTime:new Date(+now+600000)});
    await make({completedAt:now,paymentStatus:"paid"});
    await make({status:"pending"});
    await make({businessId:required._id});
    const closed = await make({status:"expired",paymentStatus:"paid"});
    await make({userId:String(other._id)});
    await make({userId:customer.firebaseUid});
    const list = (period: "upcoming"|"past"|"all"="all",page=1,limit=20) => listCustomerTicketArchive(customer,{period,page,limit},now);
    const all = await list();
    assert.deepEqual(all.counts,{upcoming:3,past:3,all:6});
    assert.equal(all.items.length,6);
    assert.ok(!JSON.stringify(all).match(/qrPayload|tokenHash|elvezet:ticket:v1|paymentScreenshotUrl/));
    const futureRow = all.items.find(item=>item.bookingId===String(future._id))!;
    assert.ok(futureRow.reference); assert.equal(futureRow.canViewReceipt,false); assert.equal(futureRow.receiptPath,null);
    assert.equal(futureRow.services[0].amount,200); assert.equal(futureRow.paymentStatus,"unpaid");
    const pastRow = all.items.find(item=>item.bookingId===String(past._id))!;
    assert.equal(pastRow.canViewTicket,true); assert.equal(pastRow.canViewReceipt,true); assert.equal(pastRow.period,"past");
    const closedRow = all.items.find(item=>item.bookingId===String(closed._id))!;
    assert.equal(closedRow.period,"past"); assert.equal(closedRow.canViewTicket,false); assert.equal(closedRow.canViewReceipt,true);
    assert.equal((await list("upcoming",1,2)).pagination.hasNextPage,true);
    assert.equal((await list("upcoming",2,2)).items.length,1);
    assert.equal((await list("upcoming",4,2)).items.length,0);
    const stable = (await list()).items.find(item=>item.bookingId===String(future._id))!;
    assert.equal(stable.reference,futureRow.reference,"Archive reads keep the same stored ticket");
    const countBefore = await BookingTicket.countDocuments();
    await Promise.all([list(),list()]);
    assert.equal(await BookingTicket.countDocuments(),countBefore,"Concurrent reads do not duplicate tickets");
    const later = await listCustomerTicketArchive(customer,{period:"past",page:1,limit:20},new Date(+now+7200000));
    assert.equal(later.items.find(item=>item.bookingId===String(future._id))?.reference,futureRow.reference,"Time moves a ticket into Past without changing it");
    const atEnd = await listCustomerTicketArchive(customer,{period:"past",page:1,limit:20},future.endTime);
    assert.ok(atEnd.items.some(item=>item.bookingId===String(future._id)),"At the exact appointment end it belongs to Past");
    await Booking.updateOne({_id:past._id},{$set:{startTime:new Date(+now+7200000),endTime:new Date(+now+9000000)}});
    const rescheduled = (await list("upcoming")).items.find(item=>item.bookingId===String(past._id))!;
    assert.equal(rescheduled.reference,pastRow.reference,"Rescheduling preserves the ticket identity");
    const get = (path:string,uid?:string) => fetch(base+path,{headers:uid?{"x-dev-user-id":uid}:{}});
    assert.equal((await get('/users/me/tickets')).status,401);
    const defaults = await get('/users/me/tickets',customer.firebaseUid);
    assert.equal(defaults.status,200); assert.match(defaults.headers.get('cache-control')!,/no-store/);
    assert.equal((await defaults.json() as any).data.pagination.limit,20);
    for(const query of ['period=bad','limit=51','page=0']) assert.equal((await get('/users/me/tickets?'+query,customer.firebaseUid)).status,400);
    const otherList = await (await get('/users/me/tickets?period=all&userId='+customer._id,other.firebaseUid)).json() as any;
    assert.equal(otherList.data.items.length,1,"Client-supplied userId never changes archive ownership");
    assert.equal((await get('/bookings/'+future._id+'/ticket',other.firebaseUid)).status,403);
    await Booking.updateOne({_id:future._id},{$set:{status:"expired"}});
    const historical = await get('/bookings/'+future._id+'/ticket',customer.firebaseUid);
    assert.equal(historical.status,200); assert.equal((await historical.json() as any).data.valid,false);
    assert.equal((await list("past")).items.find(item=>item.bookingId===String(future._id))?.reference,futureRow.reference);
    assert.equal((await get('/bookings/'+future._id+'/receipt',customer.firebaseUid)).status,409);
    const fresh = await make();
    const simultaneous = await Promise.all([list("all",1,50),list("all",1,50)]);
    const references = simultaneous.map(page=>page.items.find(item=>item.bookingId===String(fresh._id))!.reference);
    assert.equal(references[0],references[1],"Concurrent first archive reads issue the same stored ticket");
    assert.equal(await BookingTicket.countDocuments({bookingId:fresh._id}),1);
    console.log('Customer ticket archive: ownership, persistence, grouping, boundaries, pagination, legacy identities, historical access and receipt availability passed');
  } finally {
    await new Promise<void>(resolve=>server.close(()=>resolve()));
    await mongoose.connection.dropDatabase(); await mongoose.disconnect();
  }
}
main().then(()=>process.exit(0)).catch(error=>{console.error(error.message);process.exit(1);});
