import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import mongoose from "mongoose";
import env from "../config/env";
import Business from "../models/Business";
import User from "../models/User";
import StaffProfile from "../models/StaffProfile";
import Booking from "../models/Booking";
import SmsSubscription from "../models/SmsSubscription";
import SmsMessage from "../models/SmsMessage";
import { enqueueBookingSms, notifyBookingEvent } from "../services/booking-notifications.service";
import { deliverSms } from "../jobs/workers/sms.worker";
import { normalizeSmsPhone, smsProvider, SmsProviderError } from "../services/sms-provider";

async function main() {
  const database = `sms_test_${randomUUID().replaceAll("-", "").slice(0, 16)}`;
  await mongoose.connect(env.MONGO_URI, { dbName: database });
  const original = smsProvider.send;
  try {
    await Promise.all([SmsMessage.init(), SmsSubscription.init()]);
    assert.equal(normalizeSmsPhone("0911 222 333"), "+251911222333");
    assert.equal(normalizeSmsPhone("bad"), null);
    const owner = await User.create({ firebaseUid: "sms-owner", fullName: "Owner", email: "owner@example.test", phoneNumber: "+251911222333" });
    const staff = await User.create({ firebaseUid: "sms-staff", fullName: "Staff", email: "staff@example.test", phoneNumber: "+251922333444" });
    const customer = await User.create({ firebaseUid: "sms-customer", fullName: "Client", email: "client@example.test", notificationPreferences: { bookingUpdates: false } });
    const business = await Business.create({ name: "Test Shop", ownerId: owner._id, type: "shop", location: { type: "Point", coordinates: [38, 9] }, homeLocation: { type: "Point", coordinates: [38, 9] }, smsContactPhone: owner.phoneNumber });
    await StaffProfile.create({ staffId: staff.firebaseUid, businessId: business._id, isActive: true, services: [] });
    const subscription = await SmsSubscription.create({ businessId: business._id, status: "active", consentAt: new Date(), monthlyQuota: 2, periodStart: new Date(), periodEnd: new Date(Date.now() + 86400000) });
    const booking = await Booking.create({ userId: String(customer._id), businessId: business._id, staffId: staff.firebaseUid, serviceIds: [], staffPlan: [], totalAmount: 100, startTime: new Date(Date.now() + 3600000), endTime: new Date(Date.now() + 5400000), status: "pending", paymentMethod: "cash" });
    await enqueueBookingSms(String(booking._id), "booking_created");
    assert.equal(await SmsMessage.countDocuments(), 0, "Admin approval is required even for active subscriptions");
    subscription.adminEnabled = true;
    await subscription.save();
    await enqueueBookingSms(String(booking._id), "booking_created");
    assert.equal(await SmsMessage.countDocuments(), 2, "Shop and staff receive separate messages despite customer push disabled");
    await enqueueBookingSms(String(booking._id), "booking_created");
    assert.equal(await SmsMessage.countDocuments(), 2, "Replay is idempotent");
    process.env.SMS_DRY_RUN = "true";
    const messages = await SmsMessage.find();
    for (const m of messages) await deliverSms(String(m._id));
    assert.equal(await SmsMessage.countDocuments({ status: "simulated" }), 2);
    assert.equal((await SmsSubscription.findById(subscription._id))!.usedThisPeriod, 0);
    assert.equal((await SmsSubscription.findById(subscription._id))!.reservedThisPeriod, 0);
    business.smsContactPhone = staff.phoneNumber;
    await business.save();
    await enqueueBookingSms(String(booking._id), "booking_confirmed");
    assert.equal(await SmsMessage.countDocuments({ event: "booking_confirmed" }), 1, "Duplicate phone receives one SMS");
    subscription.monthlyQuota = 1; await subscription.save();
    smsProvider.send = async () => ({ providerMessageId: "mock-sent" });
    const confirmation = await SmsMessage.findOne({ event: "booking_confirmed" });
    await deliverSms(String(confirmation!._id));
    assert.equal((await SmsSubscription.findById(subscription._id))!.usedThisPeriod, 1);
    const exhausted = await SmsMessage.create({ businessId: business._id, toPhone: staff.phoneNumber, body: "Test", idempotencyKey: "quota-test", event: "booking_created" });
    await deliverSms(String(exhausted._id));
    assert.equal((await SmsMessage.findById(exhausted._id))!.status, "skipped");
    await SmsSubscription.updateOne({ _id: subscription._id }, { $set: { usedThisPeriod: 0, monthlyQuota: 1 } });
    const concurrent = await SmsMessage.create([0, 1].map(i => ({ businessId: business._id, toPhone: staff.phoneNumber, body: "Test", idempotencyKey: `concurrent-${i}`, event: "booking_created" })));
    await Promise.all(concurrent.map(m => deliverSms(String(m._id))));
    assert.equal(await SmsMessage.countDocuments({ _id: { $in: concurrent.map(m => m._id) }, status: "sent" }), 1, "Concurrent workers cannot overspend quota");
    assert.equal((await SmsSubscription.findById(subscription._id))!.reservedThisPeriod, 0);
    await SmsSubscription.updateOne({ _id: subscription._id }, { $set: { monthlyQuota: 10 } });
    smsProvider.send = async () => { throw new Error("fake_provider_down"); };
    const failure = await SmsMessage.create({ businessId: business._id, toPhone: staff.phoneNumber, body: "Test", idempotencyKey: "failure-test", event: "booking_created" });
    for (let attempt = 0; attempt < 5; attempt++) await assert.rejects(deliverSms(String(failure._id)), /sms_delivery_failed/);
    assert.equal((await SmsMessage.findById(failure._id))!.status, "failed");
    assert.equal((await SmsSubscription.findById(subscription._id))!.reservedThisPeriod, 0, "Failed sends release reserved quota");
    smsProvider.send = async () => { throw new SmsProviderError("smsethiopia_10007", "permanent"); };
    const rejected = await SmsMessage.create({ businessId: business._id, toPhone: staff.phoneNumber, body: "Test", idempotencyKey: "whitelist-test", event: "booking_created" });
    await assert.rejects(deliverSms(String(rejected._id)));
    assert.equal((await SmsMessage.findById(rejected._id))!.status, "failed");
    assert.equal((await SmsMessage.findById(rejected._id))!.reason, "smsethiopia_10007");
    let sends = 0;
    smsProvider.send = async () => { sends++; return { providerMessageId: "unexpected-send" }; };
    const interrupted = await SmsMessage.create({ businessId: business._id, toPhone: staff.phoneNumber, body: "Test", idempotencyKey: "uncertain-test", event: "booking_created", status: "sending", providerAttemptedAt: new Date(), leaseUntil: new Date(0) });
    await deliverSms(String(interrupted._id));
    assert.equal((await SmsMessage.findById(interrupted._id))!.status, "unknown");
    assert.equal(sends, 0, "An uncertain provider attempt is never blindly resent");
    await SmsSubscription.updateOne({ _id: subscription._id }, { $set: { usedThisPeriod: 0, monthlyQuota: 1 } });
    const multipart = await SmsMessage.create({ businessId: business._id, toPhone: staff.phoneNumber, body: "A".repeat(161), idempotencyKey: "multipart-test", event: "booking_created" });
    await deliverSms(String(multipart._id));
    assert.equal((await SmsMessage.findById(multipart._id))!.status, "skipped");
    assert.equal(sends, 0, "Multipart SMS cannot exceed segment quota");
    business.type = "independent"; business.smsContactPhone = owner.phoneNumber; await business.save();
    const second = await Booking.create({ userId: String(customer._id), businessId: business._id, staffId: String(owner._id), serviceIds: [], staffPlan: [], totalAmount: 100, startTime: booking.startTime, endTime: booking.endTime, status: "pending", paymentMethod: "cash" });
    await enqueueBookingSms(String(second._id), "booking_created");
    assert.equal(await SmsMessage.countDocuments({ bookingId: second._id }), 1, "Independent receives one SMS");
    await SmsSubscription.updateOne({ _id: subscription._id }, { $set: { status: "paused" } });
    await enqueueBookingSms(String(second._id), "booking_confirmed");
    assert.equal(await SmsMessage.countDocuments({ bookingId: second._id, event: "booking_confirmed" }), 0);
    await notifyBookingEvent(String(second._id), "booking_confirmed");
    await new Promise(resolve => setTimeout(resolve, 100));
    assert.ok((await Booking.findById(second._id))!.notificationEvents?.includes("booking_confirmed"), "Events persist when Redis/push is unavailable");
    assert.equal((await Booking.findById(second._id))!.status, "pending", "Notification failure never mutates booking");
    console.log("SMS integration passed: recipients, dedupe, simulation, quota, subscription isolation, durable events");
  } finally {
    smsProvider.send = original;
    if (mongoose.connection.name !== database || !database.startsWith("sms_test_")) throw new Error("Refusing unsafe database cleanup");
    await mongoose.connection.dropDatabase();
    await mongoose.disconnect();
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
